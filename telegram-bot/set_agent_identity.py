# =========================================================
# INSTALL
# =========================================================

def install():

    if not DATABASE_URL:

        raise RuntimeError(
            "DATABASE_URL is missing."
        )


    prompt = build_agent_prompt()


    # =====================================================
    # مهم جداً:
    #
    # نستخدم نفس MASTER_PROMPT_VERSION الموجود بالكود.
    #
    # لأن main.py إذا وجد Version مختلف،
    # قد يعيد كتابة Master Prompt الأصلي عند التشغيل.
    #
    # بهذه الطريقة تعتبر قاعدة البيانات محدثة
    # ولا يتم استبدال XPAND Prompt عند كل Restart.
    # =====================================================

    prompt_version = str(
        main.MASTER_PROMPT_VERSION
        or
        ""
    ).strip()


    if not prompt_version:

        raise RuntimeError(
            "MASTER_PROMPT_VERSION is missing."
        )


    with psycopg.connect(
        DATABASE_URL
    ) as conn:

        with conn.cursor() as cur:

            # =============================================
            # MASTER SYSTEM PROMPT
            # =============================================

            cur.execute(
                """
                INSERT INTO kemo_config
                (
                    config_key,
                    config_value,
                    updated_at
                )
                VALUES
                (
                    'master_system_prompt',
                    %s,
                    NOW()
                )
                ON CONFLICT(config_key)
                DO UPDATE SET
                    config_value =
                        EXCLUDED.config_value,
                    updated_at =
                        NOW();
                """,
                (
                    prompt,
                )
            )


            # =============================================
            # MASTER PROMPT VERSION
            # =============================================

            cur.execute(
                """
                INSERT INTO kemo_config
                (
                    config_key,
                    config_value,
                    updated_at
                )
                VALUES
                (
                    'master_system_prompt_version',
                    %s,
                    NOW()
                )
                ON CONFLICT(config_key)
                DO UPDATE SET
                    config_value =
                        EXCLUDED.config_value,
                    updated_at =
                        NOW();
                """,
                (
                    prompt_version,
                )
            )


        conn.commit()


    print("")
    print(
        "=============================================="
    )
    print(
        " XPAND V2 IDENTITY INSTALLED"
    )
    print(
        "=============================================="
    )
    print(
        f"✅ Company: {COMPANY_NAME}"
    )
    print(
        f"✅ Company Arabic: {COMPANY_NAME_AR}"
    )
    print(
        f"✅ Agent Identity: {AGENT_NAME}"
    )
    print(
        f"✅ Owner: {OWNER_NAME}"
    )
    print(
        "✅ Old Karim identity overridden"
    )
    print(
        "✅ Palestinian / Levantine Arabic enabled"
    )
    print(
        "✅ Serious communication style enabled"
    )
    print(
        "✅ Master Prompt updated"
    )
    print(
        "✅ Same identity shared with Call"
    )
    print(
        "✅ Text + Voice + Call identity unified"
    )
    print(
        "✅ Internal KEMO_* names preserved safely"
    )
    print(
        "=============================================="
    )
    print("")


